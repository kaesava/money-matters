import { transactionLedger, envelopes, bankAccounts, DbOrTx, getEnvelopeBalancesMap } from "@money-matters/db";
import { eq, and } from "drizzle-orm";
import { z } from "zod";
import { MoveMoneyCommand } from "@money-matters/types";
import { randomUUID } from "crypto";

export async function moveMoneyCommand(
  input: z.infer<typeof MoveMoneyCommand>,
  tenantId: string,
  appId: string,
  userId: string,
  dbClient: DbOrTx
) {
  if (input.sourceEnvelopeId === input.destinationEnvelopeId) {
    throw new Error("Cannot move money to the same envelope.");
  }

  return await dbClient.transaction(async (tx) => {
    // 1. Verify access to source envelope
    const [sourceRow] = await tx
      .select({
        envelope: envelopes,
        bankAccountIsPrivate: bankAccounts.isPrivate,
        bankAccountUserId: bankAccounts.userId,
      })
      .from(envelopes)
      .leftJoin(bankAccounts, eq(envelopes.bankAccountId, bankAccounts.id))
      .where(
        and(
          eq(envelopes.id, input.sourceEnvelopeId),
          eq(envelopes.tenantId, tenantId),
          eq(envelopes.appId, appId)
        )
      );

    if (!sourceRow) {
      throw new Error("Source envelope invalid or access unauthorized.");
    }

    const sourceEnv = (sourceRow as any).envelope ?? sourceRow;

    if (
      (sourceEnv.isPrivate && sourceEnv.userId !== userId) ||
      (sourceRow.bankAccountIsPrivate && sourceRow.bankAccountUserId !== userId)
    ) {
      throw new Error("Unauthorized: Cannot move money from partner's private envelope.");
    }

    // 2. Verify access to destination envelope
    const [destRow] = await tx
      .select({
        envelope: envelopes,
        bankAccountIsPrivate: bankAccounts.isPrivate,
        bankAccountUserId: bankAccounts.userId,
      })
      .from(envelopes)
      .leftJoin(bankAccounts, eq(envelopes.bankAccountId, bankAccounts.id))
      .where(
        and(
          eq(envelopes.id, input.destinationEnvelopeId),
          eq(envelopes.tenantId, tenantId),
          eq(envelopes.appId, appId)
        )
      );

    if (!destRow) {
      throw new Error("Destination envelope invalid or access unauthorized.");
    }

    const destEnv = (destRow as any).envelope ?? destRow;

    if (
      (destEnv.isPrivate && destEnv.userId !== userId) ||
      (destRow.bankAccountIsPrivate && destRow.bankAccountUserId !== userId)
    ) {
      throw new Error("Unauthorized: Cannot move money to partner's private envelope.");
    }

    // 3. Verify sufficient balance in source envelope
    const balancesMap = await getEnvelopeBalancesMap(tenantId, appId, tx);

    const sourceBalance = balancesMap[input.sourceEnvelopeId] || 0;
    const transferAmount = parseFloat(input.amount);

    if (sourceBalance < transferAmount) {
      throw new Error(`Insufficient funds in ${sourceEnv.name}. Available: $${sourceBalance.toFixed(2)}, requested: $${transferAmount.toFixed(2)}.`);
    }

    const cleanUserNote = input.note?.trim();
    const isAutoGenerated = cleanUserNote && (
      cleanUserNote.startsWith("Transfer:") ||
      cleanUserNote.startsWith("Transfer from ")
    );
    const debitNote = cleanUserNote && !isAutoGenerated
      ? cleanUserNote
      : `Transfer to ${destEnv.name}`;
    const creditNote = cleanUserNote && !isAutoGenerated
      ? cleanUserNote
      : `Transfer from ${sourceEnv.name}`;
    const timestamp = new Date();
    const commonId = input.idempotencyKey || randomUUID();
    const debitKey = `move-debit-${commonId}`;
    const creditKey = `move-credit-${commonId}`;

    // Check if transfer with client idempotency key was already executed
    if (input.idempotencyKey) {
      const [existingRow] = await tx
        .select({ id: transactionLedger.id })
        .from(transactionLedger)
        .where(
          and(
            eq(transactionLedger.tenantId, tenantId),
            eq(transactionLedger.idempotencyKey, debitKey)
          )
        )
        .limit(1);

      if (existingRow?.id) {
        return { success: true };
      }
    }

    // 4. Bulk insert DEBIT and CREDIT transactions in single SQL statement
    await tx.insert(transactionLedger).values([
      {
        envelopeId: input.sourceEnvelopeId,
        bankAccountId: sourceEnv.bankAccountId,
        flowType: "DEBIT",
        transactionType: "TRANSFER_OUT",
        amount: input.amount,
        idempotencyKey: debitKey,
        transferGroupId: commonId,
        note: debitNote,
        source: "MANUAL",
        recordedAt: timestamp,
        tenantId,
        appId,
        createdBy: userId,
        updatedBy: userId,
      },
      {
        envelopeId: input.destinationEnvelopeId,
        bankAccountId: destEnv.bankAccountId,
        flowType: "CREDIT",
        transactionType: "TRANSFER_IN",
        amount: input.amount,
        idempotencyKey: creditKey,
        transferGroupId: commonId,
        note: creditNote,
        source: "MANUAL",
        recordedAt: timestamp,
        tenantId,
        appId,
        createdBy: userId,
        updatedBy: userId,
      },
    ]);

    return { success: true };
  });
}
